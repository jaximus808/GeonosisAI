"""Generate ``rdf_common/spacetime_tables.py`` (typed row dataclasses + reducer wrappers) from
the published SpacetimeDB schema (TDM-16).

    cd services/common && uv run python -m rdf_common.spacetime_codegen            # live /schema
    uv run python -m rdf_common.spacetime_codegen --schema-file schema.json        # offline

Normally run through ``make gen-bindings`` (TS + Python in one go). It reads the *published*
database, so publish the module first. Host/db come from SPACETIME_HOST / SPACETIME_DB_NAME
(env or the repo .env); no token is needed.
"""

from __future__ import annotations

import argparse
import json
import keyword
import sys
from pathlib import Path

from rdf_common.spacetime_client import Schema, SpacetimeConfig, load_dotenv, _ID, _TS, _CONN, _DUR, _option_inner, _special

OUT = Path(__file__).with_name("spacetime_tables.py")


def _camel(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def _ident(name: str) -> str:
    return name + "_" if keyword.iskeyword(name) else name


def py_type(schema: Schema, ty: dict) -> str:
    ty = schema.resolve(ty)
    sp = _special(ty)
    if sp == _TS:
        return "Micros"
    if sp in (_ID, _CONN):
        return "str"
    if sp == _DUR:
        return "int"
    inner = _option_inner(ty)
    if inner is not None:
        return f"{py_type(schema, inner)} | None"
    if "Array" in ty:
        el = schema.resolve(ty["Array"])
        return "bytes" if "U8" in el else f"list[{py_type(schema, el)}]"
    if "Product" in ty:
        return "dict[str, Any]"
    if "Sum" in ty:
        return "Any"
    (prim,) = ty.keys()
    if prim in ("Bool",):
        return "bool"
    if prim in ("F32", "F64"):
        return "float"
    if prim == "String":
        return "str"
    return "int"  # I8..U256


def render(schema: Schema, source: str) -> str:
    out: list[str] = []
    w = out.append
    w('"""GENERATED by `make gen-bindings` (rdf_common.spacetime_codegen) - do not edit.')
    w("")
    w(f"Source: {source}")
    w("Typed rows for every SpacetimeDB table, plus thin typed reducer wrappers. Rows are what")
    w("rdf_common.spacetime_client decodes: Option -> None, Timestamp -> int micros, Identity -> hex str.")
    w('"""')
    w("")
    w("from __future__ import annotations")
    w("")
    w("from dataclasses import dataclass, fields")
    w("from typing import Any, Protocol")
    w("")
    w("Micros = int  # Timestamp: microseconds since the Unix epoch (see spacetime_client.ts_to_datetime)")
    w("")
    w("")
    w("class _RowMixin:")
    w("    @classmethod")
    w("    def from_row(cls, row: dict[str, Any]):")
    w("        names = {f.name: f.metadata.get('col', f.name) for f in fields(cls)}  # type: ignore[arg-type]")
    w("        return cls(**{n: row.get(c) for n, c in names.items()})")
    w("")
    w("    def to_row(self) -> dict[str, Any]:")
    w("        return {f.metadata.get('col', f.name): getattr(self, f.name) for f in fields(self)}  # type: ignore[arg-type]")
    w("")
    row_types = []
    for tname in sorted(schema.tables):
        info = schema.tables[tname]
        cls = _camel(tname)
        row_types.append((tname, cls))
        w("")
        access = "public" if info["public"] else "private"
        pk = ", ".join(info["primary_key"]) or "none"
        w("@dataclass(slots=True)")
        w(f"class {cls}(_RowMixin):")
        w(f'    """Row of `{tname}` ({access}; primary key: {pk})."""')
        w("")
        w(f'    TABLE = "{tname}"')
        w(f"    PRIMARY_KEY = {tuple(info['primary_key'])!r}")
        for col, ty in info["columns"]:
            ident = _ident(col)
            if ident != col:
                w(f"    {ident}: {py_type(schema, ty)} = field(metadata={{'col': '{col}'}})")
            else:
                w(f"    {col}: {py_type(schema, ty)}")
        w("")
    w("")
    w("ROW_TYPES: dict[str, type] = {")
    for tname, cls in row_types:
        w(f'    "{tname}": {cls},')
    w("}")
    w("")
    w("")
    w("class _Caller(Protocol):")
    w("    def call_reducer(self, name: str, *args: Any) -> Any: ...")
    w("")
    w("")
    w("class Reducers:")
    w('    """Typed wrappers: ``Reducers(SpacetimeClient()).append_event(actor=..., ...)``.')
    w("")
    w("    Works with SpacetimeClient (returns None), AsyncSpacetimeClient (returns an awaitable)")
    w('    and Subscription (socket call; returns an awaitable request id)."""')
    w("")
    w("    def __init__(self, client: _Caller):")
    w("        self._c = client")
    for rname in sorted(schema.reducers):
        if rname in ("init",) or rname.startswith("__"):
            continue  # lifecycle reducers are not client-callable
        params = schema.reducers[rname]
        sig = "".join(f", {_ident(p)}: {py_type(schema, t)}" for p, t in params)
        args = "".join(f", {_ident(p)}" for p, _ in params)
        w("")
        w(f"    def {_ident(rname)}(self{', *' if params else ''}{sig}) -> Any:")
        w(f'        return self._c.call_reducer("{rname}"{args})')
    w("")
    w("")
    w(f"TABLES = {tuple(sorted(schema.tables))!r}")
    w(f"PUBLIC_TABLES = {tuple(sorted(t for t, i in schema.tables.items() if i['public']))!r}")
    w(f"REDUCERS = {tuple(sorted(schema.reducers))!r}")
    w("")
    text = "\n".join(out)
    if "field(metadata" in text:
        text = text.replace("from dataclasses import dataclass, fields", "from dataclasses import dataclass, field, fields")
    return text


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--schema-file", help="read the schema JSON from a file instead of GET /schema")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    if a.schema_file:
        raw = json.loads(Path(a.schema_file).read_text())
        source = f"schema file {Path(a.schema_file).name}"
    else:
        import httpx

        load_dotenv()
        cfg = SpacetimeConfig.resolve(token="")
        r = httpx.get(f"{cfg.base}/schema", params={"version": 9}, timeout=20)
        r.raise_for_status()
        raw = r.json()
        source = f"{cfg.host} database {cfg.db} (published /schema)"
    schema = Schema(raw)
    Path(a.out).write_text(render(schema, source))
    print(f"[gen:bindings] python: {len(schema.tables)} tables, {len(schema.reducers)} reducers -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
